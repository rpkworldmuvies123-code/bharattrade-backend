import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import rateLimit from 'express-rate-limit';
import {connectDB} from './db.js';
import authRoutes from './routes/auth.js';
import marketRoutes from './routes/market.js';
import accountRoutes from './routes/account.js';
import orderRoutes from './routes/orders.js';
const app=express();
app.disable('x-powered-by');
const allowed=(process.env.FRONTEND_URL||'http://localhost:5173').split(',').map(s=>s.trim());
app.use(cors({origin(origin,cb){if(!origin||allowed.includes(origin))return cb(null,true);return cb(new Error('Origin not allowed by CORS'));},credentials:false}));
app.use(express.json({limit:'20kb'}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false}),authRoutes);
app.get('/api/health',(_req,res)=>res.json({ok:true,service:'BharatTrade API',mode:'paper-trading',timestamp:new Date().toISOString()}));
app.use('/api/market',marketRoutes);
app.use('/api/account',accountRoutes);
app.use('/api/orders',orderRoutes);
app.use((req,res)=>res.status(404).json({error:'Route not found'}));
app.use((err,_req,res,_next)=>{console.error(err.message);res.status(500).json({error:'Internal server error'});});
const port=Number(process.env.PORT)||5000;
connectDB().then(()=>app.listen(port,'0.0.0.0',()=>console.log(`BharatTrade API listening on ${port}`))).catch(()=>{console.error('Server not started because database connection failed. Check MONGODB_URI.');process.exit(1);});
